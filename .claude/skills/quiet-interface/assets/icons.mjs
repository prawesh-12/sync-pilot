// Writes a local icon module from Hugeicons' stroke rounded set, read through the Iconify API.
// The app then ships only the SVG bodies it uses, depends on no icon package and makes no
// request for icons at run time.
//
// Usage: copy into the project (for example scripts/icons.mjs), edit GLYPHS and OUTPUT, then
//   node scripts/icons.mjs
// Render each body inside <svg viewBox="0 0 24 24" data-icon fill="none">. The data-icon
// attribute lets the stylesheet keep the stroke at 1.5 px at every size.

import { writeFile } from "node:fs/promises";

const SET = "hugeicons";
const OUTPUT = new URL("../src/icons/glyphs.ts", import.meta.url);

/** The app's name for each icon, and the Hugeicons name drawn for it. */
const GLYPHS = {
  Add: "add-01",
  ArrowLeft: "arrow-left-02",
  Check: "tick-02",
  ChevronDown: "arrow-down-01",
  ChevronRight: "arrow-right-01",
  Close: "cancel-01",
  Copy: "copy-01",
  Ellipsis: "more-horizontal",
  ExternalLink: "link-square-02",
  Filter: "filter-horizontal",
  Home: "home-01",
  Inbox: "inbox",
  Search: "search-01",
  Settings: "settings-01",
  SidebarLeft: "sidebar-left",
  SlidersHorizontal: "sliders-horizontal",
  StatusDone: "checkmark-circle-02",
  StatusFailed: "cancel-circle",
  StatusIdle: "circle",
  Trash: "delete-02",
};

async function fetchSet(names) {
  const url = `https://api.iconify.design/${SET}.json?icons=${names.join(",")}`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Iconify answered ${response.status} for ${url}`);
  const data = await response.json();
  if (data.not_found?.length) throw new Error(`not in ${SET}: ${data.not_found.join(", ")}`);
  return data;
}

function bodyOf(data, name) {
  let current = name;
  for (let hop = 0; hop < 5 && data.icons[current] === undefined; hop += 1) {
    current = data.aliases?.[current]?.parent;
  }
  const icon = data.icons[current];
  if (icon === undefined) throw new Error(`no body for ${name}`);
  if ((icon.width ?? data.width ?? 24) !== 24 || (icon.height ?? data.height ?? 24) !== 24) {
    throw new Error(`${name} is not drawn on the 24 px grid`);
  }
  return icon.body;
}

const data = await fetchSet([...new Set(Object.values(GLYPHS))]);
const entries = Object.entries(GLYPHS).sort(([a], [b]) => a.localeCompare(b));
const lines = [
  "// Generated from Hugeicons (https://hugeicons.com, MIT) through Iconify. Edit the list in",
  "// the generator script and run it again; do not edit this file by hand.",
  "",
  "export const glyphs = {",
  ...entries.map(([name, icon]) => `  ${name}: ${JSON.stringify(bodyOf(data, icon))},`),
  "} as const;",
  "",
  "export type GlyphName = keyof typeof glyphs;",
  "",
];
await writeFile(OUTPUT, lines.join("\n"));
console.log(`wrote ${entries.length} icons to ${OUTPUT.pathname}`);
